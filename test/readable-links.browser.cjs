const assert = require('node:assert/strict'),fs = require('node:fs'),path = require('node:path'),{pathToFileURL} = require('node:url');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true});
 try {
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce',offline:true});
  const page=await context.newPage(),errors=[],requests=[];
  page.setDefaultTimeout(8000);page.on('pageerror',e=>errors.push(e.message));
  context.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url());});
  await page.goto(pathToFileURL(path.resolve(__dirname,'../index.html')).href);
  await page.waitForSelector('#main-accordion > .accordion-item',{state:'attached'});
  await page.evaluate(()=>{
   const d=UniversalManual.debug.getManualData();
   const url='https://example.invalid/a_(b)?a=1&b=2#part';
   const text='Read ('+url+').\n**https://example.invalid/bold**\nImage URL HTTP://example.invalid/picture.png\nexample LinkTermTrial\njavascript:alert(1) data:text/html,<script>window.__unsafe=true</script>\n';
   const image=(id,offset,width=65)=>({id,url:'data:image/svg+xml,'+encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" width="240" height="120"><rect width="240" height="120" fill="#b8dfef"/><circle cx="60" cy="60" r="40" fill="#307f9c"/><text x="120" y="65">Image</text></svg>'),offset,width});
   const table=()=>({rows:1,cols:2,cells:[['See '+url,'Image URL http://example.invalid/cell.png']],cellImages:[[[image('cell-a',0)],[image('cell-b',0)]]]});
   d.menu.unshift({title:'URL trial',content:text,images:[image('before',0,40),image('between',text.indexOf('Image URL'),55),image('after',text.length,70)],tables:[table()],children:[]});
   d.menu.find(x=>x.isReferenceSection).children.push({title:'LinkSourceTrial',content:'Reference '+url,images:[image('reference',0)],tables:[table()],children:[]});
   d.menu.find(x=>x.isDictionarySection).children.push({title:'LinkTermTrial',content:'Dictionary '+url,images:[image('dictionary',0)],tables:[table()],children:[]},{title:'example',content:'Dictionary term in ordinary text',children:[]});
   d.globalTabs[0].content='Global '+url+'\n{{LinkSourceTrial}}';d.globalTabs[0].images=[image('global',0)];
   localStorage.setItem(UniversalManual.debug.getActiveStorageKey(),JSON.stringify(d));localStorage.setItem('universalManual.panelLayout','body');
  });
  await page.reload();
  const trial=page.locator('#main-accordion > .accordion-item').first();
  await trial.locator(':scope > .accordion-header .accordion-toggle').click();
  const content=trial.locator(':scope > .accordion-content'),pre=content.locator(':scope > pre');
  const snapshot=await page.evaluate(()=>JSON.stringify(UniversalManual.debug.getManualData()));
  const original=await page.evaluate(()=>JSON.parse(JSON.stringify(UniversalManual.debug.getManualData().menu[0])));
  assert.equal(await content.locator('a.manual-url').count(),5);
  assert.equal(await content.locator('img.embedded-image').count(),5);
  assert.equal(await content.locator('img a,a img,a a,a .dictionary-term').count(),0,'images and dictionary terms are not nested in links');
  assert.equal(await pre.locator('strong > a.manual-url').count(),1,'formatting survives');
  assert.equal(await pre.locator('a.manual-url').first().textContent(),'https://example.invalid/a_(b)?a=1&b=2#part');
  assert.equal(await pre.locator('a.manual-url').nth(2).getAttribute('href'),'http://example.invalid/picture.png','text image URL stays an ordinary link');
  assert.equal(await content.locator('script').count(),0);assert.equal(await page.evaluate(()=>window.__unsafe),undefined);
  assert.equal(await pre.locator('.dictionary-term').count(),2,'ordinary dictionary words still link');
  for(const anchor of await content.locator('a.manual-url').all()){assert.equal(await anchor.getAttribute('target'),'_blank');assert.equal(await anchor.getAttribute('rel'),'noopener noreferrer');}
  assert.equal(requests.length,0,'rendering links makes no external requests');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'long URLs do not overflow the page');
  assert.equal(await page.evaluate(()=>JSON.stringify(UniversalManual.debug.getManualData())),snapshot);
  await pre.locator('img.embedded-image').first().dblclick();
  await page.waitForSelector('#image-lightbox');assert.equal(await page.locator('#image-lightbox a').count(),0);
  await page.locator('#image-lightbox').click({position:{x:2,y:2}});
  await pre.locator('.dictionary-term').filter({hasText:'LinkTermTrial'}).click();
  await page.waitForSelector('#dictionary-panel:not([hidden])');
  assert.equal(await page.locator('#dictionary-body a.manual-url').count(),3,'dictionary text and table paths');
  assert.equal(await page.locator('#dictionary-body img').count(),3);
  await page.locator('[aria-label="사전 닫기"]').click();
  await page.locator('#mode-toggle').click();
  assert.equal(await content.locator('a').count(),0,'editor never inserts automatic links');
  assert.equal(await content.locator('img.embedded-image').count(),5);
  assert((await pre.textContent()).includes('https://example.invalid/a_(b)?a=1&b=2#part'));
  await page.locator('#mode-toggle').click();
  assert.equal(await page.evaluate(()=>JSON.stringify(UniversalManual.debug.getManualData())),snapshot,'round trip preserves source and image offsets');
  await page.locator('#mode-toggle').click();
  const suffix='\nhttps://example.invalid/appended?x=3&y=4';
  await pre.evaluate((el,suffix)=>{el.append(document.createTextNode(suffix));el.dispatchEvent(new InputEvent('input',{bubbles:true,inputType:'insertText',data:suffix}));},suffix);
  await page.locator('#mode-toggle').click();
  assert.equal(await page.evaluate(()=>UniversalManual.debug.getManualData().menu[0].content),original.content+suffix);
  assert.deepEqual(await page.evaluate(()=>JSON.parse(JSON.stringify(UniversalManual.debug.getManualData().menu[0].images))),original.images,'appending a URL preserves attachment metadata');
  assert.equal(await content.locator('a.manual-url').count(),6);
  const openSettings=async()=>{await page.locator('#menu-toggle').click();await page.locator('#settings-open').click();};
  const setLayout=async value=>{await openSettings();await page.locator('#settings-panel-layout').selectOption(value);await page.locator('#settings-close').click();};
  await setLayout('global');
  assert.equal(await page.locator('#global-content a.manual-url').count(),4,'global and expanded reference text/table paths');
  assert.equal(await page.locator('#global-content img').count(),4);
  await page.locator('#mode-toggle').click();
  assert.equal(await page.locator('#global-content a').count(),0);
  assert.equal(await page.locator('#global-content .editable-reference-token').count(),1,'atomic reference is preserved in edit mode');
  await page.locator('#mode-toggle').click();
  await setLayout('body');
  for(const theme of ['modern','oldAndFaithful','boringAndCliche','matrix','pixel']){
   await openSettings();await page.locator('#settings-theme input[value="'+theme+'"]').check();await page.locator('#settings-close').click();
   assert.equal(await content.locator('a.manual-url').count(),6,theme);
   assert.equal(await content.locator('a.manual-url').first().evaluate(el=>getComputedStyle(el).textDecorationLine.includes('underline')),true);
  }
  await openSettings();await page.locator('#settings-theme input[value="modern"]').check();await page.locator('#settings-close').click();
  await page.locator('#main-accordion').evaluate(el=>{el.parentElement.scrollTop=0;});
  const screenshot=path.resolve(__dirname,'../preview-readable-links.png');if(fs.existsSync(screenshot))fs.copyFileSync(screenshot,path.resolve(__dirname,'../preview-readable-links_BU.png'));await page.screenshot({path:screenshot});
  await context.route('https://example.invalid/**',route=>route.fulfill({status:200,contentType:'text/html',body:'<title>Controlled link target</title>'}));
  const initialUrl=page.url(),newPage=context.waitForEvent('page');
  await pre.locator('a.manual-url').first().click();
  const popup=await newPage;await popup.waitForLoadState('domcontentloaded');
  assert.equal(await popup.evaluate(()=>window.opener),null,'new tab cannot control the manual');
  assert.equal(page.url(),initialUrl);assert.equal(await content.locator('a.manual-url').count(),6);
  await popup.close();
  await page.setViewportSize({width:1440,height:960});
  await page.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));
  assert.equal(await content.locator('a.manual-url').count(),6);
  assert.deepEqual(errors,[]);
  console.log('PASS: HTTP links, punctuation/query/formatting, no implicit requests, images before/between/after URLs, table images, lightbox, dictionary, edit round trip, append with stable offsets, global/reference paths, themes, controlled new tab without opener, offline HTML');
 } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
